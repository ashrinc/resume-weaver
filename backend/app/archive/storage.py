"""Object storage for archived PDFs: local disk or a private Supabase bucket.

Chosen by ``STORAGE_BACKEND`` ("local" default, "supabase"). The database
stores only the object key (``<uuid hex>.pdf``), never a path or a URL.
Downloads always stream through the backend; no public or signed URLs.

* ``save(key, chunks)`` consumes an async byte iterator. If the iterator
  raises (the service validates while streaming), nothing is left behind.
* ``open(key)`` checks the object exists (``StorageNotFoundError`` if not)
  and returns an async iterator of chunks.
* ``delete(key)`` is idempotent: a missing object is not an error.

Supabase uses the Storage REST API with plain ``httpx`` and the service-role
key (server side only; it never reaches the frontend).
"""

from __future__ import annotations

import re
from collections.abc import AsyncIterator
from pathlib import Path
from typing import TYPE_CHECKING, Protocol
from urllib.parse import quote

import anyio
import httpx

if TYPE_CHECKING:
    from app.config import Settings

__all__ = [
    "LocalStorage",
    "Storage",
    "StorageError",
    "StorageNotFoundError",
    "SupabaseStorage",
    "build_storage",
    "valid_key",
]

CHUNK_BYTES = 1024 * 1024
_KEY_RE = re.compile(r"^[0-9a-f]{32}\.pdf$")


class StorageError(Exception):
    """The storage backend failed. Messages never contain keys or credentials."""


class StorageNotFoundError(StorageError):
    """The object does not exist."""


def valid_key(key: str) -> bool:
    """Keys are generated by the service; anything else is refused."""
    return bool(_KEY_RE.fullmatch(key))


def _check_key(key: str) -> None:
    if not valid_key(key):
        raise StorageNotFoundError("invalid object key")


class Storage(Protocol):
    async def init(self) -> None: ...
    async def save(self, key: str, chunks: AsyncIterator[bytes]) -> int: ...
    async def open(self, key: str) -> AsyncIterator[bytes]: ...
    async def delete(self, key: str) -> None: ...


# --------------------------------------------------------------------------
# Local disk
# --------------------------------------------------------------------------


class LocalStorage:
    """``<root>/<key>``. Writes go to ``<key>.part`` and are renamed when done."""

    def __init__(self, root: Path) -> None:
        self.root = Path(root)

    async def init(self) -> None:
        await anyio.Path(self.root).mkdir(parents=True, exist_ok=True)

    def path(self, key: str) -> Path:
        _check_key(key)
        root = self.root.resolve()
        path = (root / key).resolve()
        if not path.is_relative_to(root):
            raise StorageNotFoundError("invalid object key")
        return path

    async def save(self, key: str, chunks: AsyncIterator[bytes]) -> int:
        final = self.path(key)
        part = final.with_name(final.name + ".part")
        size = 0
        try:
            async with await anyio.open_file(part, "wb") as out:
                async for chunk in chunks:
                    size += len(chunk)
                    await out.write(chunk)
            await anyio.Path(part).rename(final)
        except BaseException:
            await _unlink(part)
            raise
        return size

    async def open(self, key: str) -> AsyncIterator[bytes]:
        path = self.path(key)
        if not await anyio.Path(path).is_file():
            raise StorageNotFoundError("object not found")

        async def stream() -> AsyncIterator[bytes]:
            async with await anyio.open_file(path, "rb") as f:
                while chunk := await f.read(CHUNK_BYTES):
                    yield chunk

        return stream()

    async def delete(self, key: str) -> None:
        try:
            await _unlink(self.path(key))
        except StorageNotFoundError:
            pass


async def _unlink(path: Path) -> None:
    try:
        await anyio.Path(path).unlink(missing_ok=True)
    except OSError:
        pass


# --------------------------------------------------------------------------
# Supabase Storage (private bucket, REST API)
# --------------------------------------------------------------------------


class SupabaseStorage:
    """Objects in a private Supabase bucket, accessed with the service-role key."""

    def __init__(
        self,
        url: str,
        service_key: str,
        bucket: str,
        *,
        client: httpx.AsyncClient | None = None,
        timeout: float = 30.0,
    ) -> None:
        self.base = url.rstrip("/") + "/storage/v1"
        self.bucket = bucket
        self._headers = {"Authorization": f"Bearer {service_key}", "apikey": service_key}
        self._client = client
        self._timeout = timeout

    def _http(self) -> httpx.AsyncClient:
        if self._client is None:
            self._client = httpx.AsyncClient(timeout=self._timeout)
        return self._client

    def _object_url(self, key: str, *, authenticated: bool = False) -> str:
        _check_key(key)
        middle = "object/authenticated" if authenticated else "object"
        return f"{self.base}/{middle}/{quote(self.bucket, safe='')}/{key}"

    async def init(self) -> None:
        """Nothing to create: the private bucket is made in the Supabase dashboard."""

    async def save(self, key: str, chunks: AsyncIterator[bytes]) -> int:
        # Uploads are at most 10 MB and validated while streaming, so buffer
        # them: if validation fails, nothing is ever sent to Supabase.
        body = bytearray()
        async for chunk in chunks:
            body.extend(chunk)
        resp = await self._request(
            "POST",
            self._object_url(key),
            content=bytes(body),
            headers={"Content-Type": "application/pdf", "x-upsert": "false"},
        )
        if resp.status_code >= 300:
            raise StorageError(f"Supabase upload failed (HTTP {resp.status_code}).")
        return len(body)

    async def open(self, key: str) -> AsyncIterator[bytes]:
        resp = await self._request("GET", self._object_url(key, authenticated=True))
        if _is_not_found(resp):
            raise StorageNotFoundError("object not found")
        if resp.status_code >= 300:
            raise StorageError(f"Supabase download failed (HTTP {resp.status_code}).")
        data = resp.content

        async def stream() -> AsyncIterator[bytes]:
            for i in range(0, len(data), CHUNK_BYTES):
                yield data[i : i + CHUNK_BYTES]

        return stream()

    async def delete(self, key: str) -> None:
        resp = await self._request("DELETE", self._object_url(key))
        if resp.status_code >= 300 and not _is_not_found(resp):
            raise StorageError(f"Supabase delete failed (HTTP {resp.status_code}).")

    async def close(self) -> None:
        if self._client is not None:
            await self._client.aclose()

    async def _request(self, method: str, url: str, **kwargs: object) -> httpx.Response:
        headers = {**self._headers, **kwargs.pop("headers", {})}  # type: ignore[dict-item]
        try:
            return await self._http().request(method, url, headers=headers, **kwargs)  # type: ignore[arg-type]
        except httpx.HTTPError as exc:
            raise StorageError(
                f"Could not reach Supabase Storage ({type(exc).__name__})."
            ) from None


def _is_not_found(resp: httpx.Response) -> bool:
    if resp.status_code == 404:
        return True
    # Supabase Storage reports a missing object as HTTP 400 with a 404 body.
    if resp.status_code == 400:
        try:
            body = resp.json()
        except ValueError:
            return False
        return str(body.get("statusCode")) == "404" or body.get("error") == "not_found"
    return False


# --------------------------------------------------------------------------
# Factory
# --------------------------------------------------------------------------


def build_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "supabase":
        missing = [
            name
            for name, value in (
                ("SUPABASE_URL", settings.supabase_url),
                ("SUPABASE_SERVICE_KEY", settings.supabase_service_key),
                ("SUPABASE_BUCKET", settings.supabase_bucket),
            )
            if not value.strip()
        ]
        if missing:
            raise ValueError(
                f"STORAGE_BACKEND=supabase needs {', '.join(missing)} in backend/.env."
            )
        return SupabaseStorage(
            settings.supabase_url, settings.supabase_service_key, settings.supabase_bucket
        )
    return LocalStorage(settings.archive_upload_dir)
